    fun getRecents(context: Context): List<String> {
        val prefs = context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
        val saved = prefs.getString(KEY_RECENTS, null) ?: return SMILEYS.take(24)
        return saved.split(",").filter { it.isNotEmpty() }.ifEmpty { SMILEYS.take(24) }
    }

    fun addRecent(context: Context, emoji: String) {
        val prefs = context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
        val current = getRecents(context).toMutableList()
        current.remove(emoji)
        current.add(0, emoji)
        val trimmed = current.take(32)
        prefs.edit().putString(KEY_RECENTS, trimmed.joinToString(",")).apply()
    }
